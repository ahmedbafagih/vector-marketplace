const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const source=fs.readFileSync(__dirname+'/../Web/native.js','utf8');
const jobs=[{kind:'poll',state:'running',routineOnly:true}];
let immediate=0,routine=0;
const c=vm.createContext({nativeState:{jobs},routineRenderPending:false,saveSoon(){immediate++},saveRoutineSoon(){routine++}});
vm.runInContext(source.split('\n').find(line=>line.startsWith('function saveAfterRender(')),c);
c.saveAfterRender();
assert.equal(routine,1,'a running routine poll batches render persistence');
jobs[0].state='done';
c.routineRenderPending=true;
c.saveAfterRender();
assert.equal(routine,2,'the completion render for an unchanged poll stays batched');
assert.equal(c.routineRenderPending,false,'the completion exception applies to one render');
c.saveAfterRender();
assert.equal(immediate,1,'ordinary user and automation renders persist immediately');
console.log('PASS routine poll renders batch full-workspace writes without delaying ordinary saves');

let now=1000,scheduled=[],flushed=0;
const timerContext=vm.createContext({Date:{now:()=>now},nativeReady:true,lastSaveCompletedAt:900,routineSaveTimer:null,setTimeout(fn,delay){scheduled.push({fn,delay});return scheduled.length},saveSoon(){flushed++}});
vm.runInContext(source.split('\n').find(line=>line.startsWith('function saveRoutineSoon(')),timerContext);
timerContext.saveRoutineSoon();
timerContext.saveRoutineSoon();
assert.equal(scheduled.length,1,'repeated routine changes share one persistence timer');
assert.equal(scheduled[0].delay,299900,'routine persistence waits only for the remainder of five minutes');
scheduled[0].fn();
assert.equal(flushed,1,'the batched timer eventually flushes the workspace');
timerContext.lastSaveCompletedAt=-300000;
timerContext.saveRoutineSoon();
assert.equal(flushed,2,'an overdue routine change saves immediately');
console.log('PASS routine persistence coalesces repeated checks and flushes at five minutes');
