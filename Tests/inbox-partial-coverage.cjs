const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const listing={id:1,name:'Oak Chair',view:'Selling',importedLive:true,liveURL:'https://www.facebook.com/marketplace/item/1/'};
const work={enabled:true,leads:[],conversationProgress:{candidates:[],reads:{},censusComplete:true}};
const jobs=[],queued=[];
const rowsFor=(count,text)=>Array.from({length:count},(_,i)=>({label:'Buyer '+i+'\nOak Chair\n'+text,person:'Buyer '+i,listing:'Oak Chair',preview:text}));
let inboxRows=rowsFor(12,'old'),aiCalls=0;
const c=vm.createContext({Date,Map,Set,String,JSON,Error,Array,Object,rows:[listing],nativeState:{jobs},monitoringWanted:()=>true,workFor:()=>work,delay:async()=>{},saveSoon(){},render(){},queueJob:(kind,r,extra)=>queued.push({kind,itemId:r.id,...extra}),nativeCall:async method=>method==='observeInbox'?{url:'https://www.facebook.com/marketplace/inbox?targetTab=SELLER',inboxRows}:{},infer:async()=>{aiCalls++;throw Error('AI must not run during inbox polling')}});
vm.runInContext(fs.readFileSync(__dirname+'/../Web/conversations.js','utf8'),c);
(async()=>{
 await c.pollInbox({kind:'poll'});
 assert.equal(c.nativeState.inboxMatchedSelling,12);
 assert.equal(queued.length,0);
 inboxRows=rowsFor(4,'new reply');
 const first={kind:'poll'};await c.pollInbox(first);
 assert.match(first.completionNote,/4 matched.*4 changed.*partial inbox coverage/);
 assert.equal(c.nativeState.inboxMatchedSelling,12);
 assert.equal(queued.length,1,'visible incoming messages must be processed on the first partial poll');
 const second={kind:'poll'};await c.pollInbox(second);
 assert.match(second.completionNote,/4 matched.*0 changed.*partial inbox coverage/);
 assert.equal(queued.length,1,'unchanged partial reads do not duplicate work');
 const third={kind:'poll'};await c.pollInbox(third);
 assert.match(third.completionNote,/4 matched.*0 changed/);
 assert.equal(c.nativeState.inboxMatchedSelling,4);
 assert.equal(queued.length,1);
 assert.equal(queued[0].kind,'sync');
 assert.equal(queued[0].targetCandidateKeys.length,4);
 assert.equal(c.nativeState.metrics.partialInboxPolls,3);
 assert.equal(aiCalls,0);
 inboxRows=rowsFor(12,'new reply');await c.pollInbox({kind:'poll'});assert.equal(queued.length,2);assert.equal(queued[1].targetCandidateKeys.length,8,'newly loaded rows are processed without repeating the first four');assert.equal(Object.keys(work.inboxFingerprints).length,12,'partial reads retain unseen fingerprints');assert.equal(aiCalls,0);
 console.log('PASS partial inbox coverage processes visible changes immediately without duplicate reads or polling AI');
})().catch(e=>{console.error(e);process.exitCode=1});
