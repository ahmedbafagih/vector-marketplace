const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/../Web/native.js','utf8');
let id=0;
const c=vm.createContext({Date,Set,crypto:{randomUUID:()=>String(++id)},nativeState:{jobs:[]},compactJobs(){},saveSoon(){},saveRoutineSoon(){},addActivity(){},render(){}});
vm.runInContext(source.split('\n').find(line=>line.startsWith('function queueJob(')),c);
const item={id:1};
const partial=c.queueJob('sync',item,{incremental:true,targetCandidateKeys:['alice']});
assert.equal(c.queueJob('sync',item),partial);
assert.equal(partial.incremental,undefined,'full sync promotes the queued partial check');
assert.equal(partial.targetCandidateKeys,undefined,'full sync must not retain a one-buyer filter');
c.queueJob('sync',item,{incremental:true,targetCandidateKeys:['bob']});
assert.equal(partial.incremental,undefined,'a later inbox change must not narrow full sync');
partial.state='done';
const running=c.queueJob('sync',item,{incremental:true,targetCandidateKeys:['alice']});running.state='running';
const full=c.queueJob('sync',item);
assert(full&&full!==running,'a full request survives an already running partial check');
assert.equal(c.queueJob('sync',item),full,'repeated full requests coalesce');
assert.equal(running.incremental,true,'do not mutate an in-flight read');
full.state='running';
assert.equal(c.queueJob('sync',item),undefined,'an in-flight full scan covers another full request');
const changed=c.queueJob('sync',item,{incremental:true,targetCandidateKeys:['bob']});
c.queueJob('sync',item,{incremental:true,targetCandidateKeys:['carol']});
assert.deepEqual([...changed.targetCandidateKeys],['bob','carol'],'new messages arriving during a scan retain both follow-up targets');
console.log('PASS full sync requests retain scope around queued and running incremental checks');

vm.runInContext(source.split('\n').find(line=>line.startsWith('function jobPriority(')),c);
assert.equal(partial.prioritizeMessages,true,'a changed thread promotes a pending full scan without narrowing it');
assert.deepEqual([...partial.preferredCandidateKeys],['bob']);
assert(c.jobPriority(partial)<c.jobPriority({kind:'sync'}));
assert(c.jobPriority({kind:'sync',incremental:true})<c.jobPriority({kind:'sync'}));
assert(c.jobPriority({kind:'reply'})<c.jobPriority(partial));
