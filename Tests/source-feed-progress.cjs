const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/../Web/sourcing.js','utf8');
const c=vm.createContext({URL,Map,Date,Object,String,Array,nativeState:{sourceFeeds:{},sourceFeedOrder:[]},validListingURL:url=>/^https:\/\/www\.facebook\.com\/marketplace\/item\/\d+\/$/.test(url)});
for(const name of ['sourceCardSummary','sourceURLKey','sourceFeedDelta','rememberSourceFeed'])vm.runInContext(source.split('\n').find(line=>line.startsWith('function '+name+'(')),c);
const card=id=>({url:'https://www.facebook.com/marketplace/item/'+id+'/',text:'iPhone '+id+' CA$100'});
const feed={listings:[card(1),card(2),card(3)]};
let delta=c.sourceFeedDelta('iphone',feed);
assert.equal(delta.changed.length,3);
c.rememberSourceFeed('iphone',delta.cards,[card(1).url]);
delta=c.sourceFeedDelta('iphone',feed);
assert.equal(delta.known,true);
assert.deepEqual(Array.from(delta.changed,x=>x.url),[card(2).url,card(3).url]);
c.rememberSourceFeed('iphone',delta.cards,[card(2).url]);
delta=c.sourceFeedDelta('iphone',feed);
assert.deepEqual(Array.from(delta.changed,x=>x.url),[card(3).url]);
feed.listings[0].text='iPhone 1 CA$80';
delta=c.sourceFeedDelta('iphone',feed);
assert.deepEqual(Array.from(delta.changed,x=>x.url),[card(1).url,card(3).url]);
c.nativeState.sourceFeeds={};c.nativeState.sourceFeedOrder=[];
for(let i=0;i<80;i++)c.rememberSourceFeed('query-'+i,[card(i+10)],[card(i+10).url]);
assert(c.nativeState.sourceFeeds['query-0'],'the cache retains a complete multi-query rotation');
c.rememberSourceFeed('query-80',[card(100)],[card(100).url]);
assert.equal(c.nativeState.sourceFeeds['query-0'],undefined);assert(c.nativeState.sourceFeeds['query-1']);
console.log('PASS sourcing advances through unresearched cards and rechecks changed cards');
