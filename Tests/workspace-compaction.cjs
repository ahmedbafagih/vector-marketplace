const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/../Web/native.js','utf8');
const compact=source.slice(source.indexOf('function compactStoredText('),source.indexOf('function queueJob('));
const latest='Can I collect this evening?';
const progress={candidates:Array.from({length:140},(_,i)=>({key:'buyer-'+i})),reads:{buyer:{lead:{last:latest},proof:{text:'x'.repeat(8000)+latest+'y'.repeat(8000),listings:Array.from({length:20},(_,i)=>({url:String(i)}))}}}};
const jobProgress=JSON.parse(JSON.stringify(progress));
const row={id:7,importedLive:true,category:'unknown',inventoryNote:'n'.repeat(900),researchHistory:Array.from({length:5},(_,i)=>({id:i,steps:Array.from({length:30},()=>('s'.repeat(800))),observations:Array.from({length:15},(_,j)=>({url:String(j),text:'o'.repeat(5000),listings:[{url:'discard'}]}))}))};
const c=vm.createContext({nativeState:{jobs:[{id:'j',itemId:7,state:'done',note:'j'.repeat(3000),browserActions:Array.from({length:40},(_,i)=>({action:'click',note:'x'.repeat(900),id:i})),observations:['discard'],importProgress:{evidence:'discard',excluded:[{name:'Restricted chair',quote:'This listing may go against our rules.',reason:'Restricted'}]},conversationProgress:jobProgress}],activity:[{text:'a'.repeat(900)}],importReview:{}},listingWork:{7:{last:'w'.repeat(900),conversationProgress:progress}},rows:[row]});
vm.runInContext('function compactJobs(){}\n'+compact,c);
c.compactWorkspace();
assert.equal(c.nativeState.jobs[0].conversationProgress,undefined,'job does not duplicate listing conversation progress');
assert.equal(c.listingWork[7].conversationProgress.candidates.length,120);
assert(c.listingWork[7].conversationProgress.reads.buyer.proof.text.includes(latest),'latest verified message is retained');
assert(c.listingWork[7].conversationProgress.reads.buyer.proof.text.length<=6000);
assert.equal(c.listingWork[7].conversationProgress.reads.buyer.proof.listings.length,8);
assert.equal(c.rows[0].category,'Marketplace');
assert.equal(c.rows[0].researchHistory.length,3);
assert.equal(c.rows[0].researchHistory[0].steps.length,24);
assert.equal(c.rows[0].researchHistory[0].observations.length,12);
assert.equal(c.rows[0].researchHistory[0].observations[0].listings,undefined);
assert(c.rows[0].researchHistory[0].observations[0].text.length<=3000);
assert(c.nativeState.jobs[0].note.length<=2000);
assert.equal(c.nativeState.jobs[0].browserActions.length,5);
assert.equal(c.nativeState.jobs[0].browserActions[0].note.length,500);
assert.equal(c.nativeState.jobs[0].observations,undefined);
assert.equal(c.nativeState.jobs[0].importProgress,undefined);
assert.equal(c.nativeState.restrictedListings[0].name,'Restricted chair');
assert(c.nativeState.restrictedListings[0].quote.includes('against our rules'));
assert(c.nativeState.activity[0].text.length<=500);
console.log('PASS legacy workspace compacts evidence, removes duplicate checkpoints and retains the latest verified message');
